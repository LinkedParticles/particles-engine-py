"""Documentation-projection pipeline — render a manifest into a cited doc.

For each derived section, in manifest order:

1. **Select** candidate particles by running the section's binding through
   ``operations.query.retrieve_ranked`` with the current-truth filter pinned
   (:func:`_select_section_particles`, §3).
2. **Synthesise** the section as cited prose via the ``article_synthesis`` engine
   (Layer-A/B guard rails + deterministic fallback), or — in the drift-gate /
   key-free mode — emit a deterministic structured listing of the selection.
3. **Assemble** the rendered sections and the mechanical blocks into the full
   document in manifest order.

The **drift gate** (``project <manifest> --check``) regenerates the document in
deterministic mode and compares it to the committed snapshot: deterministic
selection + document structure hard-fail on drift; LLM prose drift is advisory
(fork #3). Deterministic mode needs neither an API key nor an embedding
model, so the gate runs in CI.

Engine layer: reads the store, runs query + synthesis, calls the LLM.
"""

