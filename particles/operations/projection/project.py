#: Sentinel format strings + parse regexes. Hoisted to the
#: Client-layer ``particles.render.markdown`` so the harvest-side
#: strip imports them downward; these aliases keep this module's call sites
#: (and its documented back-compat surface) unchanged.
_SPLICE_BEGIN = PROJECTED_BEGIN_TMPL
_SPLICE_END = PROJECTED_END_TMPL
_SPLICE_BEGIN_RE_TMPL = PROJECTED_BEGIN_RE_TMPL
_SPLICE_END_RE_TMPL = PROJECTED_END_RE_TMPL


class SpliceError(ValueError):
    """A block-splice could not be performed against the target file.

    Raised when the named region is missing, when a BEGIN sentinel has no
    matching END (or vice versa), or when the region appears more than once.
    The message names the region and the failure so an operator can fix the
    target file by hand.
    """


def splice_region(existing: str, region: str, new_body: str, *, manifest: str) -> str:
    """Replace the text between a named sentinel pair, preserving everything else.

    The block-splice contract. ``existing`` is the full current text of a
    hand-authored file carrying exactly one sentinel pair for ``region``::

        <!-- BEGIN PROJECTED: architecture (manifest: docs/projection/x.yaml) -->
        … old projected content …
        <!-- END PROJECTED: architecture -->

    Returns ``existing`` with the content *between* the sentinels replaced by
    ``new_body`` (the sentinels themselves are rewritten so the ``manifest:``
    attribution stays current), and all content outside the pair preserved
    byte-for-byte. The operation is idempotent: re-splicing a file that already
    carries the pair replaces the body cleanly and keeps a single pair.

    Raises :class:`SpliceError` when the region is missing, when a BEGIN has no
    matching END, or when ``region`` appears more than once (each is a target-file
    authoring mistake, not a recoverable case).
    """
    begin_re = re.compile(_SPLICE_BEGIN_RE_TMPL.format(region=re.escape(region)))
    end_re = re.compile(_SPLICE_END_RE_TMPL.format(region=re.escape(region)))

    begins = list(begin_re.finditer(existing))
    ends = list(end_re.finditer(existing))

    if len(begins) > 1 or len(ends) > 1:
        raise SpliceError(
            f"projection region {region!r} appears more than once in the target file "
            f"({len(begins)} BEGIN / {len(ends)} END sentinels); a region must be unique."
        )
    if not begins and not ends:
        raise SpliceError(
            f"projection region {region!r} not found in the target file. Add the sentinel "
            f"pair:\n  {_SPLICE_BEGIN.format(region=region, manifest=manifest)}\n  "
            f"{_SPLICE_END.format(region=region)}"
        )
    if not begins:
        raise SpliceError(
            f"projection region {region!r} has an END sentinel but no matching BEGIN."
        )
    if not ends:
        raise SpliceError(f"projection region {region!r} has a BEGIN sentinel but no matching END.")

    begin, end = begins[0], ends[0]
    if end.start() < begin.end():
        raise SpliceError(
            f"projection region {region!r} has its END sentinel before its BEGIN sentinel."
        )

    new_begin = _SPLICE_BEGIN.format(region=region, manifest=manifest)
    new_end = _SPLICE_END.format(region=region)
    body = new_body.strip("\n")
    replacement = f"{new_begin}\n{body}\n{new_end}" if body else f"{new_begin}\n{new_end}"
    return existing[: begin.start()] + replacement + existing[end.end() :]


async def project_document(
    session: AsyncSession,
    manifest: DocManifest,
    *,
    base_dir: Path,
    synthesize: bool,
) -> ProjectionResult:
    """Render a manifest into one Markdown document.

    ``synthesize=True`` renders each derived section as LLM-cited clean prose
    (requires an API key; falls back per-section to the deterministic listing on
    failure). ``synthesize=False`` is the deterministic, key-free, embedding-free
    render used by ``--without-synthesis`` and the drift gate — byte-stable for a
    given store, which is what makes the gate enforceable.
    """
    parts: list[str] = [_BANNER.format(name=manifest.name)]
    any_synth = False
    backrefs: dict[str, str] | None = None

    for section in manifest.sections:
        if isinstance(section, MechanicalBlock):
            parts.append(_render_block(section, base_dir))
            continue

        # A bullets section is deterministic by definition:
        # embedding-free selection, no synthesis, regardless of `synthesize`.
        bullets = section.render == "bullets"
        particles = await _select_section_particles(
            session, section, use_embeddings=synthesize and not bullets
        )
        header = f"## {section.title}\n"
        if not particles:
            log.warning("projection: section %r selected no particles", section.title)
            parts.append(f"{header}\n_No current particles match this section's binding._\n")
            continue

        if bullets:
            if backrefs is None:
                backrefs = await get_inconsistency_backrefs(session)
            badges = await _bullet_badges(session, particles, backrefs)
            body = _bullet_section_part(
                section, particles, header="", backrefs=backrefs, badges=badges
            ).render()
        elif synthesize:
            body, used = await _synthesised_section_body(
                session, section, particles, manifest.name, framing=manifest.framing
            )
            any_synth = any_synth or used
        else:
            body = _deterministic_section_body(particles)
        parts.append(f"{header}\n{body.rstrip()}\n")

    document = "\n".join(part.rstrip("\n") for part in parts) + "\n"
    return ProjectionResult(document=document, used_synthesis=any_synth)


async def project_splice_body(
    session: AsyncSession,
    manifest: DocManifest,
    *,
    base_dir: Path,
    synthesize: bool,
) -> ProjectionResult:
    """Render a manifest's *body* for splicing into a sentinel region.

    Like :func:`project_document` but tailored for the block-splice write mode:
    it omits the document banner (the host file is hand-authored) and, for a
    single-section manifest, omits the ``## <title>`` heading — the host file's
    hand-authored heading above the sentinels owns it (the ADR §1 layout puts
    ``## Architecture`` *outside* the block). A multi-section manifest keeps its
    per-section headings, since the block then carries more than one section.

    The README-architecture slice is single-section, so the spliced region is
    pure projected prose plus its sources trailer — exactly what sits under the
    hand-authored ``## Architecture`` heading.
    """
    single_section = len(manifest.sections) == 1
    parts: list[str | _BulletSectionPart] = []
    any_synth = False
    backrefs: dict[str, str] | None = None

    for section in manifest.sections:
        if isinstance(section, MechanicalBlock):
            parts.append(_render_block(section, base_dir))
            continue
        header = "" if single_section else f"## {section.title}\n\n"
        part, used, backrefs = await _derived_section_part(
            session,
            section,
            manifest,
            synthesize=synthesize,
            header=header,
            backrefs=backrefs,
        )
        any_synth = any_synth or used
        parts.append(part)

    # Document budget: enforced by the splice renderer only —
    # rank-order truncation of bullet entries, `select.allow` pins exempt.
    document = _apply_budget(parts, max_lines=manifest.max_lines, max_bytes=manifest.max_bytes)
    # A spliced host file is plain Markdown, not a wiki vault.
    return ProjectionResult(document=strip_wiki_links(document), used_synthesis=any_synth)


async def _derived_section_part(
    session: AsyncSession,
    section: DerivedSection,
    manifest: DocManifest,
    *,
    synthesize: bool,
    header: str,
    backrefs: dict[str, str] | None,
) -> tuple[str | _BulletSectionPart, bool, dict[str, str] | None]:
    """Render one derived section for a splice body.

    Shared by the single-region splice (:func:`project_splice_body`) and the
    multi-region path (:func:`project_region_bodies`). Returns
    ``(part, used_synthesis, backrefs)`` — ``backrefs`` is the lazily-loaded
    INCONSISTENCY backref cache, threaded through so a document with several
    bullets sections loads it once.
    """
    bullets = section.render == "bullets"
    particles = await _select_section_particles(
        session, section, use_embeddings=synthesize and not bullets
    )
    if bullets:
        if backrefs is None:
            backrefs = await get_inconsistency_backrefs(session)
        badges = await _bullet_badges(session, particles, backrefs)
        part = _bullet_section_part(
            section, particles, header=header, backrefs=backrefs, badges=badges
        )
        return part, False, backrefs
    if not particles:
        log.warning("projection: section %r selected no particles", section.title)
        return f"{header}_No current particles match this section's binding._\n", False, backrefs

    if synthesize:
        body, used = await _synthesised_section_body(
            session, section, particles, manifest.name, framing=manifest.framing
        )
    else:
        body, used = _deterministic_section_body(particles), False
    return f"{header}{body.rstrip()}\n", used, backrefs


async def project_region_bodies(
    session: AsyncSession,
    manifest: DocManifest,
    *,
    base_dir: Path,
    synthesize: bool,
    only_region: str | None = None,
) -> tuple[dict[str, str], bool]:
    """Render each region-bearing section's splice body separately.

    The multi-region half of the block-splice write mode: returns
    ``{region: body}`` in manifest order, each body headingless (the host
    file's hand-authored heading above the sentinels owns it) and wiki-link
    stripped, plus whether any section used LLM synthesis. ``only_region``
    restricts the render to one declared region (the ``--splice REGION``
    re-roll path on a region-bearing manifest).

    Raises ``ValueError`` when the manifest declares no regions, when
    ``only_region`` names an undeclared region, or — for the splice-all path
    (``only_region=None``) — when any derived section lacks a ``region``
    (a silently unspliced section is an authoring mistake, not a choice).
    The document budget is not applied on this path: no current
    region-bearing manifest sets one, and a budget spanning independently
    spliced regions has no defined truncation order.
    """
    regions = manifest.region_sections()
    if not regions:
        raise ValueError(f"manifest {manifest.name!r} declares no `region:` on any section")
    if only_region is not None and only_region not in regions:
        declared = ", ".join(regions)
        raise ValueError(
            f"manifest {manifest.name!r} declares no region {only_region!r} (declared: {declared})"
        )
    if only_region is None:
        unbound = [
            s.title for s in manifest.sections if isinstance(s, DerivedSection) and s.region is None
        ]
        if unbound:
            raise ValueError(
                f"--splice-all requires every derived section to declare a `region:`; "
                f"missing on: {', '.join(map(repr, unbound))}"
            )

    bodies: dict[str, str] = {}
    any_synth = False
    backrefs: dict[str, str] | None = None
    for region, section in regions.items():
        if only_region is not None and region != only_region:
            continue
        part, used, backrefs = await _derived_section_part(
            session,
            section,
            manifest,
            synthesize=synthesize,
            header="",
            backrefs=backrefs,
        )
        any_synth = any_synth or used
        body = part if isinstance(part, str) else part.render()
        bodies[region] = strip_wiki_links(body.rstrip("\n") + "\n")
    return bodies, any_synth


@dataclass(frozen=True)
class DriftResult:
    """Outcome of a drift-gate check."""

    drifted: bool
    snapshot_path: Path
    regenerated: str
    committed: str | None
    #: Region-trailer consistency failures: one message per
    #: declared region whose host-file ``<!-- sources -->`` trailer no longer
    #: matches the deterministic selection. Empty when the manifest declares no
    #: regions, the output file could not be resolved, or everything matches.
    region_issues: tuple[str, ...] = ()

    @property
    def reason(self) -> str:
        """A one-line operator explanation of the check outcome."""
        if self.region_issues:
            issues = "; ".join(self.region_issues)
            return (
                f"projected regions drifted from the store selection: {issues}. "
                "Re-splice with `particles project <manifest> --splice-all` and "
                "commit the re-blessed render."
            )
        if self.committed is None:
            return f"no committed snapshot at {self.snapshot_path} to diff against"
        if self.drifted:
            return (
                f"deterministic projection drifted from {self.snapshot_path}: the "
                "committed snapshot no longer matches the store + manifest (selection "
                "or structure changed). Regenerate with `particles project`."
            )
        return f"deterministic projection matches {self.snapshot_path}"


def snapshot_path_for(manifest: DocManifest, *, base_dir: Path) -> Path:
    """The committed deterministic-snapshot path the drift gate diffs.

    ``<base_dir>/<name>.snapshot.md`` — a sibling of the manifest. The snapshot is
    the gated contract (deterministic selection + structure); the human-facing
    ``output`` doc (LLM prose) is advisory (fork #3).
    """
    return base_dir / f"{manifest.name}.snapshot.md"


async def check_drift(
    session: AsyncSession,
    manifest: DocManifest,
    *,
    base_dir: Path,
    output_root: Path | None = None,
) -> DriftResult:
    """Regenerate the deterministic snapshot and diff it against the committed copy.

    No API key, no embedding model — the deterministic render is byte-stable for a
    given store, so this is the CI-runnable half of the gate.

    **Region-trailer consistency.** When the manifest declares
    sentinel regions and ``output_root`` is given, the check additionally parses
    the host output file and compares each declared region's ``<!-- sources -->``
    trailer id-set against that section's deterministic selection. A mismatch is
    a hard drift failure: a pin / store change must not stop at a refreshed
    snapshot — the shipped host document itself must be re-spliced (and that
    re-splice is the explicit re-blessing act). A relative ``output`` resolves
    against ``output_root`` (never the process cwd); ``output_root=None`` skips
    the region check for callers with no host-file anchor.
    """
    regenerated = (
        await project_document(session, manifest, base_dir=base_dir, synthesize=False)
    ).document
    snap_path = snapshot_path_for(manifest, base_dir=base_dir)
    committed = snap_path.read_text(encoding="utf-8") if snap_path.exists() else None

    region_issues = tuple(await _region_trailer_issues(session, manifest, output_root=output_root))
    drifted = committed is None or committed != regenerated or bool(region_issues)
    return DriftResult(
        drifted=drifted,
        snapshot_path=snap_path,
        regenerated=regenerated,
        committed=committed,
        region_issues=region_issues,
    )


def _trailer_short_ids(body: str) -> set[str] | None:
    """The ``p-<shortid>`` set from a region body's sources trailer, or None."""
    match = SOURCES_TRAILER_RE.search(body)
    if match is None:
        return None
    ids = {frag.strip() for frag in match.group("ids").split(",") if frag.strip()}
    return {_strip_pin_prefix(i) for i in ids}


async def _region_trailer_issues(
    session: AsyncSession,
    manifest: DocManifest,
    *,
    output_root: Path | None,
) -> list[str]:
    """Per-region trailer-vs-selection mismatches in the host file."""
    regions = manifest.region_sections()
    if not regions or output_root is None or manifest.output is None:
        return []
    out_path = Path(manifest.output)
    if not out_path.is_absolute():
        out_path = output_root / out_path
    if not out_path.exists():
        return [f"output file {out_path} not found (regions {', '.join(regions)} unchecked)"]

    host_regions = {r.region: r for r in find_projected_regions(out_path.read_text("utf-8"))}
    issues: list[str] = []
    for region, section in regions.items():
        host = host_regions.get(region)
        if host is None:
            issues.append(f"region {region!r} missing from {out_path.name}")
            continue
        selected = await _select_section_particles(session, section, use_embeddings=False)
        expected = {_short_id(p.id) for p, _eff in selected}
        found = _trailer_short_ids(host.body)
        if found is None:
            issues.append(f"region {region!r} in {out_path.name} has no sources trailer")
        elif found != expected:
            gone = ", ".join(sorted(expected - found)) or "-"
            extra = ", ".join(sorted(found - expected)) or "-"
            issues.append(
                f"region {region!r} in {out_path.name} cites a different claim set than "
                f"the store selection (missing: {gone}; extra: {extra})"
            )
    return issues
