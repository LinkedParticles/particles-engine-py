/*
 * Bundles src/register.tsx and the shared curation core it imports into
 * hooks/register.js, the hooks module Claude Code loads, and
 * writes the core's contract as test/contract.gen.ts for the pane's tests.
 *
 * The bundle is committed, so the plugin installs from a checkout with no
 * build. The build is deterministic: rebuilding the same sources writes the
 * same bytes, and `--check` fails when the committed bundle is stale.
 *
 *   node esbuild.config.mjs           # write hooks/register.js
 *   node esbuild.config.mjs --check   # fail if hooks/register.js is stale
 */
import esbuild from "esbuild";
import { readFileSync, writeFileSync } from "fs";

const OUT = "hooks/register.js";
const result = await esbuild.build({
  entryPoints: ["src/register.tsx"],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  write: false,
  // JSX compiles against the globals Claude Code gives a hooks module.
  jsxFactory: "h",
  jsxFragment: "Fragment",
  // Types only: the import is erased, never bundled.
  external: ["claude-code"],
  legalComments: "none",
  logLevel: "error",
});
const header =
  "// GENERATED by clients/claude-code-plugin/esbuild.config.mjs from src/ and\n" +
  "// clients/curation-core/src/. Do not edit; run `npm run build`.\n";
// Claude Code reads `register` where it is declared, so the bundle declares
// it exported in place rather than in esbuild's trailing export list.
let bundle = result.outputFiles[0].text;
const tail = /\nexport \{\n {2}register\n\};\n$/;
if (!tail.test(bundle) || !bundle.includes("\nvar register = ")) {
  throw new Error("unexpected bundle shape: cannot place `export const register`");
}
bundle = bundle.replace(tail, "\n").replace("\nvar register = ", "\nexport const register = ");
const text = header + bundle;

// The pane's tests read the core's contract. A test may import only code
// inside the plugin, so the build writes it there as a module.
const CONTRACT = "test/contract.gen.ts";
const contract =
  "// GENERATED from clients/curation-core/fixtures/contract.json by\n" +
  "// esbuild.config.mjs. Do not edit; run `npm run build`.\n" +
  "const contract: any = " +
  JSON.stringify(JSON.parse(readFileSync("../curation-core/fixtures/contract.json", "utf8"))) +
  ";\nexport default contract;\n";

const outputs = [
  [OUT, text],
  [CONTRACT, contract],
];
if (process.argv.includes("--check")) {
  let stale = false;
  for (const [path, want] of outputs) {
    let prior = "";
    try {
      prior = readFileSync(path, "utf8");
    } catch {
      /* missing counts as stale */
    }
    if (prior !== want) {
      console.error(`${path} is not the build of its sources: run npm run build and commit it`);
      stale = true;
    }
  }
  if (stale) process.exit(1);
  console.log(`${OUT} and ${CONTRACT} are current`);
} else {
  for (const [path, want] of outputs) writeFileSync(path, want);
  console.log(`wrote ${OUT} and ${CONTRACT}`);
}
